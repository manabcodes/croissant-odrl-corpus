#!/usr/bin/env python3
"""
Bulk-generate Croissant + ODRL metadata for many real Hugging Face datasets.

For each dataset:
  1. Fetch its existing Croissant metadata via HF's public /croissant endpoint
     (github.com/mlcommons/croissant support, auto-generated by HF for most
     public non-gated datasets).
  2. Look up its declared license (from the "license:xxx" tag HF puts on
     every dataset, or from cardData as a fallback) in a curated license ->
     ODRL policy registry (LICENSE_POLICIES below).
  3. Inject the corresponding spec-correct usageInfo/odrl:Offer block by
     reusing croissant_baker.odrl — the SAME code already validated against
     the 5-dataset hand-curated corpus, not a reimplementation.
  4. Save the result, and log what happened to a CSV manifest, so you can
     see exactly what was and wasn't covered and why.

Datasets whose license isn't in the registry are SKIPPED, not guessed at.
Fabricating a policy for an unrecognized license would produce a corpus
that looks complete but is actually making things up — worse than a
smaller, honest one. Extend LICENSE_POLICIES to cover more licenses.

============================================================================
IMPORTANT — WHAT IS AND ISN'T TESTED
============================================================================
The license-mapping and inject_odrl logic below reuses your actual patched
croissant_baker.odrl code and can be sanity-checked without any network
access (see the bottom of this docstring).

The HTTP calls to huggingface.co (both the bulk listing endpoint and the
per-dataset /croissant endpoint) were NOT run end-to-end in the sandbox
this was written in — huggingface.co isn't reachable from there. The
per-dataset /croissant endpoint shape IS verified against a real response
(fetched directly earlier in the conversation this was built in). The bulk
LISTING endpoint's exact field names (particularly how license shows up:
a "license:xxx" tag vs. a cardData.license field) are based on public HF
docs and long-standing convention, not a live-verified response.

Run this first, before anything larger:

    python bulk_hf_odrl_corpus.py --limit 10 --debug --dry-run

--debug prints the raw JSON of the first listing response so you can see
immediately whether the license field is where this script expects it. If
it isn't, the fix is almost certainly just editing `extract_license()`
below to match what you actually see — everything downstream (the
registry, the injection, the manifest) doesn't need to change.

============================================================================
Usage
============================================================================
Run from inside your patched croissant-baker checkout so the import of
croissant_baker.odrl resolves (or `pip install -e .` it elsewhere first):

    cd croissant-baker
    export HF_TOKEN=hf_...          # optional, raises HF rate limits
    uv run python bulk_hf_odrl_corpus.py --limit 10 --debug --dry-run
    uv run python bulk_hf_odrl_corpus.py --limit 500 --output-dir ./hf-corpus
"""

