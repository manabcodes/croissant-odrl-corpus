# Common alternate spellings seen in HF tags/cardData.
LICENSE_ALIASES = {
    "cc0": "cc0-1.0",
    "public-domain": "pddl",
    "cc-by": "cc-by-4.0",
    "cc-by-sa": "cc-by-sa-4.0",
    "cc-by-nc": "cc-by-nc-4.0",
}


def resolve_license_policy(license_id: Optional[str]) -> Optional[ODRLConfig]:
    if not license_id:
        return None
    key = license_id.strip().lower()
    key = LICENSE_ALIASES.get(key, key)
    return LICENSE_POLICIES.get(key)


def extract_license(dataset_entry: dict) -> Optional[str]:
    """Pull the license id out of one entry from the /api/datasets listing.

    Primary: the "license:xxx" tag HF has long put on tagged datasets.
    Fallback: cardData.license, when the listing was requested with full=true.
    If NEITHER matches what you see with --debug, this is the one function
    to fix.
    """
    for tag in dataset_entry.get("tags", []) or []:
        if isinstance(tag, str) and tag.startswith("license:"):
            return tag.split(":", 1)[1]

    card_data = dataset_entry.get("cardData") or {}
    license_val = card_data.get("license")
    if isinstance(license_val, list):
        return license_val[0] if license_val else None
    if isinstance(license_val, str):
        return license_val
    return None


# ── Per-dataset worker ────────────────────────────────────────────────────


@dataclass
class Result:
    dataset_id: str
    status: str  # ok | skipped_no_license | skipped_unmapped_license | skipped_no_croissant | error
    license: Optional[str] = None
    detail: str = ""


def fetch_with_retry(session: requests.Session, url: str, max_retries: int = 5) -> requests.Response:
    """Retry on 429 with exponential backoff, capped, plus jitter so
    concurrent threads don't all retry in lockstep and re-trigger the
    same rate limit they're backing off from (observed: 129/1000 errors
    were 429s even with HF_TOKEN set on a --concurrency 6 run — a
    thundering-herd pattern where simultaneous threads' retries land in
    the same window is the likely cause, not an invalid token, though
    that's worth ruling out separately)."""
    import random

    delay = 2.0
    resp = None
    for attempt in range(max_retries):
        resp = session.get(url, timeout=30)
        if resp.status_code == 429 and attempt < max_retries - 1:
            time.sleep(min(delay, 30.0) + random.uniform(0, 1.0))
            delay *= 2
            continue
        return resp
    return resp


def process_dataset(dataset_id: str, license_id: Optional[str], output_dir: Path, session: requests.Session) -> Result:
    policy = resolve_license_policy(license_id)
    if policy is None:
        status = "skipped_no_license" if not license_id else "skipped_unmapped_license"
        return Result(dataset_id, status, license_id, f"no policy mapping for '{license_id}'")

    url = CROISSANT_URL.format(repo_id=dataset_id)
    try:
        resp = fetch_with_retry(session, url)
    except requests.RequestException as e:
        return Result(dataset_id, "error", license_id, f"request failed: {e}")

    if resp.status_code == 404:
        return Result(dataset_id, "skipped_no_croissant", license_id, "no Croissant metadata available")
    if resp.status_code == 400:
        # Observed on a real 500-dataset run: consistently hit for datasets
        # whose structure Croissant auto-generation can't handle (e.g.
        # loading-script-based datasets like legacy-datasets/wikipedia,
        # rather than a plain parquet/file layout). Not a transient
        # failure — retrying won't help, so it's classified separately
        # from "error" rather than lumped in with it.
        return Result(dataset_id, "skipped_croissant_generation_failed", license_id, "HTTP 400 — dataset structure not supported by Croissant auto-generation")
    if resp.status_code == 403:
        # Also observed consistently: gated/access-restricted datasets.
        # Even a valid HF_TOKEN doesn't help unless that account has
        # separately accepted the dataset's access terms on the Hub. Not
        # a bug or a rate-limit issue — genuinely access-controlled.
        return Result(dataset_id, "skipped_gated_or_forbidden", license_id, "HTTP 403 — dataset is gated or access-restricted")
    if resp.status_code == 401:
        # Observed on a real 1000-dataset run alongside 403s — almost
        # certainly the same underlying cause (gated/access-controlled
        # dataset) surfaced as a different status code, not an invalid
        # token, since other requests on the same session/token succeeded.
        return Result(dataset_id, "skipped_gated_or_forbidden", license_id, "HTTP 401 — likely gated/access-restricted (same handling as 403)")
    if resp.status_code == 429:
        return Result(dataset_id, "error", license_id, "rate limited (429) — lower --concurrency or set HF_TOKEN")
    if resp.status_code != 200:
        return Result(dataset_id, "error", license_id, f"HTTP {resp.status_code}")

    try:
        metadata = resp.json()
    except ValueError:
        return Result(dataset_id, "error", license_id, "response was not valid JSON")

    try:
        enriched = inject_odrl(metadata, policy)
    except Exception as e:  # noqa: BLE001 — surfaced in manifest, not swallowed
        return Result(dataset_id, "error", license_id, f"inject_odrl failed: {e}")

    safe_name = dataset_id.replace("/", "__")
    out_path = output_dir / f"{safe_name}.jsonld"
    try:
        out_path.write_text(json.dumps(enriched, indent=2))
    except OSError as e:
        return Result(dataset_id, "error", license_id, f"write failed: {e}")

    return Result(dataset_id, "ok", license_id)


# ── Listing ───────────────────────────────────────────────────────────────


def list_datasets(session: requests.Session, limit: int, sort: str, debug: bool) -> list[dict]:
    """Fetch dataset listing entries, attempting Link-header pagination.

    NOTE: a real run showed this doesn't actually work — --limit 2000
    still returned exactly 1000 entries, meaning either HF sends no Link
    header for this endpoint, or paginates some other way. That guess
    (Link headers) was presented with more confidence than it deserved.
    Rather than guess a second time, this now surfaces the raw evidence
    (headers, resp.links) via --debug so the real mechanism can be
    identified from what HF actually sends back, not assumed.
    """
    entries: list[dict] = []
    url = LIST_URL
    params = {"sort": sort, "direction": -1, "limit": limit, "full": "true"}

    while url and len(entries) < limit:
        resp = session.get(url, params=params, timeout=60)
        resp.raise_for_status()
        page = resp.json()

        if debug:
            print("\n--- DEBUG: page request ---")
            print(f"  URL requested: {resp.url}")
            print(f"  status: {resp.status_code}")
            print(f"  entries returned this page: {len(page)}")
            print(f"  ALL response headers: {dict(resp.headers)}")
            print(f"  resp.links (parsed Link header, empty dict if HF sent none): {resp.links}")
            if not entries and page:
                print(f"  first entry keys: {list(page[0].keys())}")
            print("--- END DEBUG ---\n")

        entries.extend(page)

        next_url = resp.links.get("next", {}).get("url")

        if not next_url and len(page) >= 1000 and len(entries) < limit:
            print(
                f"WARNING: got {len(page)} entries in one page with no 'next' Link "
                f"header, but requested limit is {limit} and we're stopping short. "
                f"This endpoint likely doesn't paginate via Link headers — check "
                f"the --debug headers above for anything resembling a cursor, "
                f"offset, or page token instead."
            )

        url = next_url
        params = None

    return entries[:limit]


# ── Main ──────────────────────────────────────────────────────────────────


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--limit", type=int, default=500, help="Datasets to attempt (default: 500)")
    parser.add_argument("--output-dir", type=Path, default=Path("./hf-odrl-corpus"))
    parser.add_argument("--concurrency", type=int, default=6, help="Concurrent requests (default: 6 — be polite)")
    parser.add_argument("--sort", default="downloads", choices=["downloads", "likes", "createdAt", "lastModified"])
    parser.add_argument("--dry-run", action="store_true", help="List + resolve licenses only, no network fetch/writes per dataset")
    parser.add_argument("--debug", action="store_true", help="Print the raw first listing entry before processing")
    args = parser.parse_args()

    args.output_dir.mkdir(parents=True, exist_ok=True)

    token = os.environ.get("HF_TOKEN")
    if not token:
        print("No HF_TOKEN set — you'll hit rate limits sooner. export HF_TOKEN=hf_... to raise them.")

    session = requests.Session()
    if token:
        session.headers["Authorization"] = f"Bearer {token}"

    print(f"Listing up to {args.limit} datasets sorted by {args.sort}...")
    entries = list_datasets(session, args.limit, args.sort, args.debug)
    print(f"Got {len(entries)} entries.")

    if args.dry_run:
        counts = Counter()
        for e in entries:
            lic = extract_license(e)
            counts["ok" if resolve_license_policy(lic) else "unmapped/missing"] += 1
        print("\nDry run — license resolution only, no HTTP calls per dataset, no files written:")
        for status, count in counts.most_common():
            print(f"  {status}: {count}")
        unmapped = Counter(extract_license(e) for e in entries if not resolve_license_policy(extract_license(e)))
        if unmapped:
            print("\nMost common unmapped/missing licenses:")
            for lic, count in unmapped.most_common(15):
                print(f"  {lic or '(none)'}: {count}")
        return

    print("Fetching Croissant metadata and applying policies...")
    results: list[Result] = []
    with ThreadPoolExecutor(max_workers=args.concurrency) as pool:
        futures = {}
        for e in entries:
            dataset_id = e.get("id")
            if not dataset_id:
                continue
            license_id = extract_license(e)
            futures[pool.submit(process_dataset, dataset_id, license_id, args.output_dir, session)] = dataset_id

        done = 0
        for future in as_completed(futures):
            results.append(future.result())
            done += 1
            if done % 25 == 0 or done == len(futures):
                print(f"  {done}/{len(futures)}")

    manifest_path = args.output_dir / "manifest.csv"
    with open(manifest_path, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["dataset_id", "status", "license", "detail"])
        for r in results:
            writer.writerow([r.dataset_id, r.status, r.license or "", r.detail])

    counts = Counter(r.status for r in results)
    print("\nSummary")
    for status, count in counts.most_common():
        print(f"  {status}: {count}")
    print(f"\nManifest: {manifest_path}")
    print(f"Generated files: {args.output_dir}")

    unmapped = Counter(r.license for r in results if r.status == "skipped_unmapped_license")
    if unmapped:
        print("\nMost common unmapped licenses (candidates to add to LICENSE_POLICIES):")
        for lic, count in unmapped.most_common(15):
            print(f"  {lic or '(none)'}: {count}")


if __name__ == "__main__":
    main()
