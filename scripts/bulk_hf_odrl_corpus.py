LICENSE_ALIASES = {
    "cc0": "cc0-1.0",
    "public-domain": "pddl",
    "cc-by": "cc-by-4.0",
    "cc-by-sa": "cc-by-sa-4.0",
    "cc-by-nc": "cc-by-nc-4.0",
}


def resolve_license_policy(license_id: Optional[str]) -> Optional[ODRLConfig]:
    if not license_id:
        return None
    key = license_id.strip().lower()
    key = LICENSE_ALIASES.get(key, key)
    return LICENSE_POLICIES.get(key)


def extract_license(dataset_entry: dict) -> Optional[str]:
    """Pull the license id out of one entry from the /api/datasets listing.

    Primary: the "license:xxx" tag. Fallback (confirmed live to be the
    common case): cardData.license.
    """
    for tag in dataset_entry.get("tags", []) or []:
        if isinstance(tag, str) and tag.startswith("license:"):
            return tag.split(":", 1)[1]

    card_data = dataset_entry.get("cardData") or {}
    license_val = card_data.get("license")
    if isinstance(license_val, list):
        return license_val[0] if license_val else None
    if isinstance(license_val, str):
        return license_val
    return None


@dataclass
class Result:
    dataset_id: str
    status: str
    license: Optional[str] = None
    detail: str = ""


def fetch_with_retry(session: requests.Session, url: str, max_retries: int = 3) -> requests.Response:
    delay = 1.0
    for attempt in range(max_retries):
        resp = session.get(url, timeout=30)
        if resp.status_code == 429 and attempt < max_retries - 1:
            time.sleep(delay)
            delay *= 2
            continue
        return resp
    return resp


def process_dataset(dataset_id: str, license_id: Optional[str], output_dir: Path, session: requests.Session) -> Result:
    policy = resolve_license_policy(license_id)
    if policy is None:
        status = "skipped_no_license" if not license_id else "skipped_unmapped_license"
        return Result(dataset_id, status, license_id, f"no policy mapping for '{license_id}'")

    url = CROISSANT_URL.format(repo_id=dataset_id)
    try:
        resp = fetch_with_retry(session, url)
    except requests.RequestException as e:
        return Result(dataset_id, "error", license_id, f"request failed: {e}")

    if resp.status_code == 404:
        return Result(dataset_id, "skipped_no_croissant", license_id, "no Croissant metadata available")
    if resp.status_code == 400:
        return Result(dataset_id, "skipped_croissant_generation_failed", license_id, "HTTP 400 — dataset structure not supported by Croissant auto-generation")
    if resp.status_code == 403:
        return Result(dataset_id, "skipped_gated_or_forbidden", license_id, "HTTP 403 — dataset is gated or access-restricted")
    if resp.status_code == 429:
        return Result(dataset_id, "error", license_id, "rate limited (429) — lower --concurrency or set HF_TOKEN")
    if resp.status_code != 200:
        return Result(dataset_id, "error", license_id, f"HTTP {resp.status_code}")

    try:
        metadata = resp.json()
    except ValueError:
        return Result(dataset_id, "error", license_id, "response was not valid JSON")

    try:
        enriched = inject_odrl(metadata, policy)
    except Exception as e:  # noqa: BLE001
        return Result(dataset_id, "error", license_id, f"inject_odrl failed: {e}")

    safe_name = dataset_id.replace("/", "__")
    out_path = output_dir / f"{safe_name}.jsonld"
    try:
        out_path.write_text(json.dumps(enriched, indent=2))
    except OSError as e:
        return Result(dataset_id, "error", license_id, f"write failed: {e}")

    return Result(dataset_id, "ok", license_id)


def list_datasets(session: requests.Session, limit: int, sort: str, debug: bool) -> list[dict]:
    params = {"sort": sort, "direction": -1, "limit": limit, "full": "true"}
    resp = session.get(LIST_URL, params=params, timeout=60)
    resp.raise_for_status()
    entries = resp.json()

    if debug:
        print("\n--- DEBUG: raw first entry from the listing endpoint ---")
        print(json.dumps(entries[0] if entries else {}, indent=2)[:3000])
        print("--- END DEBUG ---\n")

    return entries


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--limit", type=int, default=500)
    parser.add_argument("--output-dir", type=Path, default=Path("./hf-odrl-corpus"))
    parser.add_argument("--concurrency", type=int, default=6)
    parser.add_argument("--sort", default="downloads", choices=["downloads", "likes", "createdAt", "lastModified"])
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--debug", action="store_true")
    args = parser.parse_args()

    args.output_dir.mkdir(parents=True, exist_ok=True)

    token = os.environ.get("HF_TOKEN")
    if not token:
        print("No HF_TOKEN set — you'll hit rate limits sooner. export HF_TOKEN=hf_... to raise them.")

    session = requests.Session()
    if token:
        session.headers["Authorization"] = f"Bearer {token}"

    print(f"Listing up to {args.limit} datasets sorted by {args.sort}...")
    entries = list_datasets(session, args.limit, args.sort, args.debug)
    print(f"Got {len(entries)} entries.")

    if args.dry_run:
        counts = Counter()
        for e in entries:
            lic = extract_license(e)
            counts["ok" if resolve_license_policy(lic) else "unmapped/missing"] += 1
        print("\nDry run:")
        for status, count in counts.most_common():
            print(f"  {status}: {count}")
        unmapped = Counter(extract_license(e) for e in entries if not resolve_license_policy(extract_license(e)))
        if unmapped:
            print("\nMost common unmapped/missing licenses:")
            for lic, count in unmapped.most_common(15):
                print(f"  {lic or '(none)'}: {count}")
        return

    print("Fetching Croissant metadata and applying policies...")
    results: list[Result] = []
    with ThreadPoolExecutor(max_workers=args.concurrency) as pool:
        futures = {}
        for e in entries:
            dataset_id = e.get("id")
            if not dataset_id:
                continue
            license_id = extract_license(e)
            futures[pool.submit(process_dataset, dataset_id, license_id, args.output_dir, session)] = dataset_id

        done = 0
        for future in as_completed(futures):
            results.append(future.result())
            done += 1
            if done % 25 == 0 or done == len(futures):
                print(f"  {done}/{len(futures)}")

    manifest_path = args.output_dir / "manifest.csv"
    with open(manifest_path, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["dataset_id", "status", "license", "detail"])
        for r in results:
            writer.writerow([r.dataset_id, r.status, r.license or "", r.detail])

    counts = Counter(r.status for r in results)
    print("\nSummary")
    for status, count in counts.most_common():
        print(f"  {status}: {count}")
    print(f"\nManifest: {manifest_path}")
    print(f"Generated files: {args.output_dir}")

    unmapped = Counter(r.license for r in results if r.status == "skipped_unmapped_license")
    if unmapped:
        print("\nMost common unmapped licenses (candidates to add to LICENSE_POLICIES):")
        for lic, count in unmapped.most_common(15):
            print(f"  {lic or '(none)'}: {count}")


if __name__ == "__main__":
    main()
